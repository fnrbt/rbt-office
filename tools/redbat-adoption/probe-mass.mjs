import { launch, newPage, open, T, S, SHOTS } from "./lib.mjs";
const { browser } = await launch();
const ev = (page, fn, arg) => page.evaluate(fn, arg);
const file = `${S}/long-generated.docx`;
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
const page = await newPage(ctx);
await open(page, "word-editor", file);
await page.waitForSelector('[data-testid="word-toolbar"]', { timeout: 300000 });
await page.waitForFunction(() => window.__word.isLoadComplete(window.__editors[0]) !== false, null, { timeout: 300000 });
await ev(page, () => window.__word.whenLayoutComplete(window.__editors[0]));
await page.waitForTimeout(500);
const scroll = () => ev(page, () => document.querySelector('[data-testid="word-scroll"]').scrollTop);
console.log("scrollTop", await scroll());
await ev(page, () => window.__word.getInputElement(window.__editors[0]).focus());
await page.keyboard.press("Control+a"); await page.waitForTimeout(200);
console.log("scrollTop after ctrl+a", await scroll(), JSON.stringify(await ev(page, () => window.__word.getCaretRect(window.__editors[0]))));
const r = await ev(page, () => {
  const w = window.__word, e = window.__editors[0]; const out = [];
  const step = (name, fn) => { const t = performance.now(); let v; try { v = fn(); } catch (err) { v = String(err); } out.push(`${name}: ${Math.round(performance.now() - t)} ms, complete after=${w.isLayoutComplete(e)}${name === "getCaretRect" ? " " + JSON.stringify(v) : ""}`); };
  // unsubscribe-free: the host's listener runs inside toggleBold (sets signals, queues a frame)
  step("toggleBold (+host onChange)", () => w.toggleBold(e));
  step("getSelectionFormat", () => w.getSelectionFormat(e));
  step("getCaretContext", () => w.getCaretContext(e));
  step("getDocumentSize", () => w.getDocumentSize(e));
  step("getPageFrames", () => w.getPageFrames(e).length);
  step("getCaretRect", () => w.getCaretRect(e));
  step("getPageCount", () => w.getPageCount(e));
  return out;
});
console.log(r.join("\n"));
await page.waitForTimeout(300);
console.log("scrollTop after bold", await scroll());
await browser.close();
