import { launch, newPage, open, T } from "./lib.mjs";
import { g } from "./ui-lib.mjs";
const { browser, context } = await launch();
const page = await newPage(context, { verbose: false });
await open(page, "sheet-preview", `${T}/real-world/milk-street-office.xlsx`);
await page.waitForFunction(() => document.querySelector('[data-testid="spreadsheet-preview"]')?.style.visibility === "visible", null, { timeout: 180000 });
await g(page, () => { const gr = window.__grids[0]; gr.SetReadOnly(false); window.__cm = []; gr.OnContextMenu((r) => window.__cm.push(r.target + r.row + "," + r.col)); window.__dom = []; document.addEventListener("contextmenu", (e) => window.__dom.push(e.target.className + "/" + (e.target.parentElement?.className ?? "")), true); });
const n = () => g(page, () => window.__cm.length);
const hdr = async (row, label) => { const q = await g(page, (row) => { const h = document.querySelector(`.spreadsheet-row-header[data-row="${row}"]`).getBoundingClientRect(); return [h.left + 20, h.top + 10]; }, row); const before = await n(); await page.mouse.click(q[0], q[1], { button: "right" }); await page.waitForTimeout(200); console.log(label, "-> event:", (await n()) > before, "selection", await g(page, () => window.__grids[0].GetSelectionRef()), "dom target", await g(page, () => window.__dom.at(-1))); };
await hdr(7, "1. right click row header 8");
await hdr(7, "2. the same header again");
await hdr(11, "3. another row header (12)");
await hdr(11, "4. that one again");
await g(page, () => window.__grids[0].SelectCell(3, 3));
await hdr(11, "5. after SelectCell(3,3), header 12");
await browser.close();
