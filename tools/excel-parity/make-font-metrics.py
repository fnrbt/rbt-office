#!/usr/bin/env python3
"""Writes src/Spreadsheet/FontMetricsData.fs - what Excel 2019 makes of a font at 100 % on Windows (96 dpi) - from
what was measured in Excel and GDI on the VM (tools/excel-parity/font-metrics/, docs/excel-parity-tracker.md):

- excel-normal-fonts.tsv: each font as a workbook's Normal font (face, points, maximum digit width, the row of a
  line), by its pixel size round(points x 4/3): Excel sets a font at whole pixels, and two sizes of one pixel size
  (8 and 8.5 pt: 11 px) measure the same (144 of 144 fractional sizes; probe-fonts.vbs part 3).
- excel-cell-fonts.tsv: rows of one cell of a font in sheets of a few Normal fonts, fitted by Excel (AutoFit): in
  an Arial 6 sheet, the row of a bold / italic font, where it is not the regular one's (probe-fonts.vbs part 2).
- gdi-text-metrics.tsv: GDI's TEXTMETRIC of the faces at 6 to 60 px (gdi-metrics.ps1): a font's descent
  (tmDescent), for where a row's fonts meet at their baseline (FontMetrics.lineOf).

Deterministic: run it again and the bytes are the same.

    python3 tools/excel-parity/make-font-metrics.py
"""
import collections
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'font-metrics')
OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'src', 'Spreadsheet', 'FontMetricsData.fs'))
DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def px(points):
    return math.floor(points * 4 / 3 + 0.5)


def rows_of(name):
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        return []
    return [line.rstrip('\r\n').split('\t') for line in open(path, encoding='utf-8') if line.strip() and not line.startswith('#')]


# Regular: face -> {px: (mdw, row)}
regular = collections.defaultdict(dict)
for face, points, mdw, row in rows_of('excel-normal-fonts.tsv'):
    regular[face].setdefault(px(float(points)), (int(mdw), int(row)))

# Styled rows (bold 1, italic 2, bold italic 3) from the Arial 6 sheet, where they differ from the regular row.
STYLE = {1: 'b', 2: 'i', 3: 'bi'}
measured = {}
for normal, face, points, style, lines, height, *_ in rows_of('excel-cell-fonts.tsv'):
    if normal == 'Arial|6' and lines == '1' and height != 'ERR':
        measured[(face.lower(), float(points), int(style))] = round(float(height) / 0.75)
styled = collections.defaultdict(dict)
for (face, points, style), row in sorted(measured.items()):
    if style == 0:
        continue
    plain = measured.get((face, points, 0))
    if plain is not None and row != plain:
        styled[f'{face}|{STYLE[style]}'].setdefault(px(points), row - plain)

# Descents: face|style -> tmDescent at 6..60 px (a base-36 character each); a face GDI does not have (it names
# another) is left out.
descents = {}
gdi = collections.defaultdict(dict)
for face, size, style, height, ascent, descent, internal, external, average, actual in rows_of('gdi-text-metrics.tsv'):
    if actual.lower() == face.lower():
        gdi[(face.lower(), int(style))][int(size)] = int(descent)
for (face, style), by_px in sorted(gdi.items()):
    if all(p in by_px for p in range(6, 61)):
        descents[face + '|' + ('', 'b', 'i', 'bi')[style]] = ''.join(DIGITS[by_px[p]] for p in range(6, 61))
# Aptos (an Office cloud font: GDI on the VM has it not, Excel draws it all the same): its descent rounded from the
# font's (Aptos Narrow's file: winDescent 563 of 2048 units), the rows of Aptos in a Calibri sheet as Excel's.
if gdi:
    for face in ('aptos', 'aptos narrow', 'aptos display'):
        descents[face + '|'] = ''.join(DIGITS[math.floor(563 * p / 2048 + 0.5)] for p in range(6, 61))
    # Lato (a cloud font too: winDescent 599 of 2000) and Tw Cen MT (not measured through GDI: winDescent 477 of 2048)
    # likewise; their rows measured in Excel (probe-font-faces.vbs).
    for face, units, em in (('lato', 599, 2000), ('tw cen mt', 477, 2048)):
        descents.setdefault(face + '|', ''.join(DIGITS[math.floor(units * p / em + 0.5)] for p in range(6, 61)))

lines = [
    '/// Generated by tools/excel-parity/make-font-metrics.py from what was measured in Excel 2019 and GDI',
    '/// (tools/excel-parity/font-metrics/): do not edit.',
    'module Rbt.Spreadsheet.FontMetricsData',
    '',
    '/// Face -> "px:mdw:row ..." (a pixel size, its maximum digit width and the row of a line of it, in pixels),',
    '/// each font as a workbook\'s Normal font.',
    'let regular : (string * string) list =',
    '    [ ' + '\n      '.join(f'"{face}", "' + ' '.join(f'{p}:{m}:{r}' for p, (m, r) in sorted(t.items())) + '"'
                             for face, t in sorted(regular.items())) + ' ]',
    '',
    '/// "face|b", "face|i", "face|bi" -> "px:delta ...": where the row of a bold / italic font is not the regular',
    '/// one\'s, the difference (pixels).',
    'let styled : (string * string) list =',
    ('    [ ' + '\n      '.join(f'"{key}", "' + ' '.join(f'{p}:{d}' for p, d in sorted(t.items())) + '"'
                               for key, t in sorted(styled.items())) + ' ]') if styled else '    []',
    '',
    '/// "face|style" -> GDI\'s descent (tmDescent) of the font at 6 to 60 px, a base-36 digit each.',
    'let descents : (string * string) list =',
    ('    [ ' + '\n      '.join(f'"{key}", "{text}"' for key, text in sorted(descents.items())) + ' ]') if descents else '    []',
    '',
]
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines))
print(OUT, len(regular), 'faces', len(styled), 'styled', len(descents), 'descents')
