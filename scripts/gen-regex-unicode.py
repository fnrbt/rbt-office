#!/usr/bin/env python3
"""Generate src/Spreadsheet/Functions/RegexUnicode.fs: the Unicode data the regular expression engine
(Functions/Pcre.fs) needs, the same on .NET and in the browser (neither runtime's own tables are used, as
their Unicode versions differ):

  - the general category of every code point (UnicodeData.txt, unassigned ones Cn),
  - the simple case folding (CaseFolding.txt, statuses C and S),
  - the script of every code point (Scripts.txt) and the script names and aliases
    (PropertyValueAliases.txt, `sc`).

    python3 scripts/gen-regex-unicode.py UCD_DIR > src/Spreadsheet/Functions/RegexUnicode.fs

UCD_DIR holds those files of the Unicode Character Database 16.0.0
(https://www.unicode.org/Public/16.0.0/ucd/).
"""
import os
import sys

ucd = sys.argv[1]
CATS = ["Cc", "Cf", "Cn", "Co", "Cs", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn", "Nd", "Nl", "No",
        "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm", "So", "Zl", "Zp", "Zs"]


def lines(name):
    with open(os.path.join(ucd, name), encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                yield [p.strip() for p in line.split(';')]


def b36(n):
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    if n == 0:
        return '0'
    s = ''
    while n:
        s = digits[n % 36] + s
        n //= 36
    return s


cat = [CATS.index('Cn')] * 0x110000
first = None
for p in lines('UnicodeData.txt'):
    cp = int(p[0], 16)
    c = CATS.index(p[2])
    if p[1].endswith(', First>'):
        first = cp
        continue
    if p[1].endswith(', Last>'):
        for x in range(first, cp + 1):
            cat[x] = c
        continue
    cat[cp] = c
runs = []
start = 0
for cp in range(1, 0x110001):
    if cp == 0x110000 or cat[cp] != cat[start]:
        runs.append('%s.%s' % (b36(cp - start), b36(cat[start])))
        start = cp
category_data = ','.join(runs)

folds = []
for p in lines('CaseFolding.txt'):
    if p[1] in ('C', 'S'):
        folds.append((int(p[0], 16), int(p[2], 16)))
folds.sort()
# Runs of (start, count, delta): consecutive code points (step 1 or 2) folding by the same delta.
fold_runs = []
i = 0
while i < len(folds):
    cp, to = folds[i]
    delta = to - cp
    step = 1
    if i + 1 < len(folds) and folds[i + 1][1] - folds[i + 1][0] == delta and folds[i + 1][0] - cp in (1, 2):
        step = folds[i + 1][0] - cp
    n = 1
    while i + n < len(folds) and folds[i + n][0] == cp + n * step and folds[i + n][1] - folds[i + n][0] == delta:
        n += 1
    fold_runs.append('%s.%s.%d.%s' % (b36(cp), b36(n), step, ('-' + b36(-delta)) if delta < 0 else b36(delta)))
    i += n
fold_data = ','.join(fold_runs)

aliases = {}
for p in lines('PropertyValueAliases.txt'):
    if p[0] == 'sc':
        aliases[p[2]] = [p[1]] + p[3:]
names = sorted(aliases)
script_of = {}
for p in lines('Scripts.txt'):
    rng = p[0].split('..')
    lo = int(rng[0], 16)
    hi = int(rng[-1], 16)
    for x in range(lo, hi + 1):
        script_of[x] = p[1]
# The script extensions (ScriptExtensions.txt, by short names; a code point not listed has its script),
# which is what PCRE2 (10.40 on) tests \p{script} against.
short = {aliases[n][0]: n for n in names}
extensions = {}
for p in lines('ScriptExtensions.txt'):
    rng = p[0].split('..')
    lo = int(rng[0], 16)
    hi = int(rng[-1], 16)
    for x in range(lo, hi + 1):
        extensions[x] = tuple(sorted(names.index(short[a]) for a in p[1].split()))
sets = []
script_runs = []
prev = None
start = 0
for cp in range(0, 0x110001):
    s = (extensions.get(cp) or (names.index(script_of.get(cp, 'Unknown')),)) if cp < 0x110000 else None
    if s != prev:
        if prev is not None:
            if prev not in sets:
                sets.append(prev)
            script_runs.append('%s.%s' % (b36(cp - start), b36(sets.index(prev))))
        prev = s
        start = cp
script_data = ','.join(script_runs)
script_sets = ';'.join('.'.join(b36(x) for x in st) for st in sets)
script_names = ';'.join(','.join([n] + aliases[n]) for n in names)

out = sys.stdout
out.write('''/// GENERATED by scripts/gen-regex-unicode.py from the Unicode Character Database 16.0.0: do not edit.
/// The general categories, the simple case folding and the scripts of the code points, for the regular
/// expression engine (Pcre.fs), so that .NET and the browser agree (neither runtime's tables are used).
module Rbt.Spreadsheet.Functions.RegexUnicode

/// The general categories, in the order of their numbers.
let categoryNames = [| %s |]

/// Runs of code points of one category from U+0000 on: "length.category", base 36.
let categoryData = "%s"

/// Simple case folding: "start.count.step.delta", base 36 (a negative delta "-...").
let foldData = "%s"

/// The scripts, each "Name,Alias,...", in the order of their numbers.
let scriptNames = "%s"

/// The sets of scripts code points have (their script extensions): "script.script...", base 36.
let scriptSets = "%s"

/// Runs of code points of one set of scripts from U+0000 on: "length.set", base 36.
let scriptData = "%s"
''' % ('; '.join('"%s"' % c for c in CATS), category_data, fold_data, script_names, script_sets, script_data))
